"""Run after changing site copy: pip install 'fonttools[woff]'."""
from pathlib import Path
import hashlib, html, json, re
from fontTools import subset
from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parents[1]
texts = [html.unescape(p.read_text(errors='ignore')) for p in root.rglob('*')
         if p.suffix in {'.html', '.js', '.css', '.json'}
         and '.git' not in p.parts and 'optimized' not in p.parts]
chars = ''.join(sorted(set(''.join(texts))))
source = root / 'assets/figures/hanyi-xingkai.ttf'
font = TTFont(source, recalcTimestamp=False)
expected = set(font.getBestCmap()) & set(map(ord, chars))
options = subset.Options()
options.layout_features = ['*']
subsetter = subset.Subsetter(options=options)
subsetter.populate(unicodes=expected)
subsetter.subset(font)
font.flavor = 'woff2'
# Hash the generated bytes, so long-lived cached URLs always identify one file.
temporary = root / 'assets/optimized/heading-build.woff2'
font.save(temporary)
digest = hashlib.sha256(temporary.read_bytes()).hexdigest()[:10]
target = temporary.with_name(f'hanyi-xingkai-{digest}.woff2')
temporary.replace(target)
assert expected <= set(TTFont(target).getBestCmap())
for css in (root / 'assets').glob('*.css'):
    old = css.read_text()
    new = re.sub(r'url\("(?:figures/hanyi-xingkai\.ttf|optimized/hanyi-xingkai-[a-f0-9]+\.woff2)"\) format\("(?:truetype|woff2)"\)',
                 f'url("optimized/{target.name}") format("woff2")', old)
    if new != old:
        css.write_text(new)
manifest = root / 'tools/web-assets-manifest.json'
report = json.loads(manifest.read_text())
report['font'] = {'file': str(target.relative_to(root)), 'before': source.stat().st_size,
                  'after': target.stat().st_size, 'codepoints': len(expected)}
manifest.write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n')
print(target.name, target.stat().st_size, 'bytes;', len(expected), 'codepoints')
print('Bump stylesheet query versions before publishing updated HTML.')
